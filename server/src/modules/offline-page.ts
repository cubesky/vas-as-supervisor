/**
 * Lua module shipped in the OpenResty bundle (lua/vas_offline.lua). It is
 * the target of `error_page 502 = @vas_offline` in locations that proxy to
 * workload references (compose/podman/lxc/vm): when nginx can't reach any
 * upstream, visitors get a 503 "service not running" page instead of a bare
 * 502. The page is localized from Accept-Language, JSON clients get JSON, and
 * an operator-supplied template (offline.html in the bundle) replaces the
 * default. Internal target names are deliberately not shown.
 */
export const OFFLINE_LUA = String.raw`-- generated by vas: placeholder page for offline workload upstreams
local cjson = require "cjson.safe"

local _M = {}

local MESSAGES = {
  en = { title = "Service not running", body = "The service behind %s is not running right now. Please try again in a moment." },
  ja = { title = "サービスは停止中です", body = "%s のサービスは現在稼働していません。しばらくしてから再度お試しください。" },
  ko = { title = "서비스가 실행 중이 아닙니다", body = "%s 서비스가 현재 실행 중이 아닙니다. 잠시 후 다시 시도해 주세요." },
  ["zh-TW"] = { title = "服務未執行", body = "%s 的服務目前未執行，請稍後再試。" },
  ["zh-CN"] = { title = "服务未运行", body = "%s 的服务当前未运行，请稍后再试。" },
}

local DEFAULT = [==[<!doctype html>
<html lang="{{lang}}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta http-equiv="refresh" content="15">
<title>{{title}}</title>
<style>
  body { margin: 0; min-height: 100vh; display: grid; place-items: center; background: #f4f5f7; color: #1b1f24;
         font: 16px/1.6 system-ui, -apple-system, "Segoe UI", "Hiragino Sans", "Noto Sans CJK JP", sans-serif; }
  .card { max-width: 460px; margin: 16px; padding: 32px; background: #fff; border: 1px solid #dde1e6; border-radius: 12px; text-align: center; }
  .dot { width: 12px; height: 12px; border-radius: 50%; background: #d9a03f; display: inline-block; }
  h1 { font-size: 20px; margin: 12px 0 8px; }
  p { margin: 0; color: #66707c; }
  @media (prefers-color-scheme: dark) {
    body { background: #111316; color: #e3e6ea; }
    .card { background: #1c2025; border-color: #2c323b; }
    p { color: #8b939e; }
  }
</style>
</head>
<body>
<div class="card"><span class="dot"></span><h1>{{title}}</h1><p>{{message}}</p></div>
</body>
</html>
]==]

-- operator template, read once per worker (workers restart on every reload)
local custom
local function template()
  if custom == nil then
    local f = io.open("/etc/openresty/vas/offline.html", "rb")
    if f then
      custom = f:read("*a")
      f:close()
    else
      custom = false
    end
  end
  return custom or DEFAULT
end

local ESC = { ["&"] = "&amp;", ["<"] = "&lt;", [">"] = "&gt;", ['"'] = "&quot;", ["'"] = "&#39;" }
local function esc(s)
  return (tostring(s or ""):gsub("[&<>\"']", ESC))
end

local function pick_lang()
  local al = (ngx.var.http_accept_language or ""):lower()
  for tag in al:gmatch("[%a%-]+") do
    local p = tag:sub(1, 2)
    if p == "ja" then return "ja" end
    if p == "ko" then return "ko" end
    if tag == "zh-tw" or tag == "zh-hk" or tag:find("^zh%-hant") then return "zh-TW" end
    if p == "zh" then return "zh-CN" end
    if p == "en" then return "en" end
  end
  return "en"
end

function _M.serve()
  local lang = pick_lang()
  local m = MESSAGES[lang]
  local host = ngx.var.host or ""
  local message = string.format(m.body, host)

  ngx.status = 503
  ngx.header["Retry-After"] = "15"
  ngx.header["Cache-Control"] = "no-store"

  local accept = ngx.var.http_accept or ""
  if accept:find("json", 1, true) and not accept:find("html", 1, true) then
    ngx.header["Content-Type"] = "application/json"
    ngx.say(cjson.encode({ error = "upstream_offline", message = message }))
    return
  end

  local vars = { lang = lang, title = esc(m.title), message = esc(message), host = esc(host) }
  ngx.header["Content-Type"] = "text/html; charset=utf-8"
  ngx.say((template():gsub("{{(%w+)}}", function(k) return vars[k] or "" end)))
end

return _M
`;

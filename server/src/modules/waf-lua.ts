/**
 * The WAF engine, shipped in the OpenResty bundle as lua/vas_waf.lua (so it
 * needs neither opm nor an image rebuild). Each WAF-enabled server block calls
 *
 *   local ok, verdict = pcall(require("vas_waf").check, "<route>")
 *   if verdict then return require("vas_waf").deny(verdict) end
 *
 * in its access phase; an engine error is logged and the request allowed.
 * Configuration (rules, per-route modes, exclusions, custom rules) is read
 * from waf/config.json once per worker; workers restart on every reload.
 * Events go to the vas_waf shared dict and are shipped to the manager by the
 * privileged agent process every 5 seconds.
 */
export const WAF_LUA = String.raw`-- generated by vas: web application firewall
local cjson = require "cjson.safe"
local process = require "ngx.process"

local _M = {}

local CONF = "/etc/openresty/vas/waf/config.json"
local QUEUE = ngx.shared.vas_waf
local MAX_QUEUE = 2000
local unescape = ngx.unescape_uri

local cfg
local function config()
  if cfg == nil then
    cfg = false
    local f = io.open(CONF, "rb")
    if f then
      local c = cjson.decode(f:read("*a"))
      f:close()
      if type(c) == "table" then
        c.disabled_set = {}
        for _, id in ipairs(c.disabled or {}) do c.disabled_set[id] = true end
        for _, r in pairs(c.routes or {}) do
          r.excluded_set = {}
          for _, id in ipairs(r.excludeRules or {}) do r.excluded_set[id] = true end
        end
        cfg = c
      end
    end
  end
  return cfg
end

-- values are URL-decoded twice to see through double encoding
local function decode(s)
  if type(s) ~= "string" then return "" end
  local d = unescape(s)
  if d:find("%", 1, true) then d = unescape(d) end
  return d
end

local function flatten(args, out)
  for k, v in pairs(args or {}) do
    out[#out + 1] = decode(tostring(k))
    if type(v) == "table" then
      for _, x in ipairs(v) do
        if type(x) == "string" then out[#out + 1] = decode(x) end
      end
    elseif type(v) == "string" then
      out[#out + 1] = decode(v)
    end
  end
  return out
end

-- request body: only small, textual bodies that are already in memory
local INSPECTABLE = { "x-www-form-urlencoded", "json", "xml", "text/", "graphql" }
local function body_values()
  local method = ngx.req.get_method()
  if method == "GET" or method == "HEAD" or method == "OPTIONS" then return {} end
  local len = tonumber(ngx.var.content_length)
  local limit = (config() or {}).bodyLimit or 65536
  if not len or len == 0 or len > limit then return {} end
  local ct = (ngx.var.content_type or ""):lower()
  local ok = false
  for _, t in ipairs(INSPECTABLE) do
    if ct:find(t, 1, true) then ok = true break end
  end
  if not ok then return {} end
  ngx.req.read_body()
  if ct:find("x-www-form-urlencoded", 1, true) then
    return flatten(ngx.req.get_post_args(100), {})
  end
  local data = ngx.req.get_body_data()
  return data and { data } or {}
end

local getters = {
  uri = function() return { ngx.var.uri or "" } end,
  raw_uri = function() return { decode(ngx.var.request_uri or "") } end,
  args = function() return flatten(ngx.req.get_uri_args(100), {}) end,
  body = body_values,
  cookies = function()
    local out, c = {}, ngx.var.http_cookie
    if c then
      for v in c:gmatch("[^;]+") do out[#out + 1] = decode(v) end
    end
    return out
  end,
  ua = function() return { ngx.var.http_user_agent or "" } end,
  referer = function()
    local r = ngx.var.http_referer
    return r and { decode(r) } or {}
  end,
  headers = function()
    local out = {}
    for k, v in pairs(ngx.req.get_headers(64) or {}) do
      if k ~= "cookie" then
        if type(v) == "table" then
          for _, x in ipairs(v) do out[#out + 1] = x end
        else
          out[#out + 1] = v
        end
      end
    end
    return out
  end,
  method = function() return { ngx.req.get_method() } end,
  ip = function() return { ngx.var.remote_addr or "" } end,
}

local function event(route_id, rc, action, score, hits)
  return {
    ts = ngx.now(),
    route = route_id,
    host = ngx.var.host,
    ip = ngx.var.remote_addr,
    method = ngx.req.get_method(),
    uri = (ngx.var.request_uri or ""):sub(1, 512),
    ua = (ngx.var.http_user_agent or ""):sub(1, 256),
    action = action,
    mode = rc.mode,
    score = score,
    rules = hits,
    requestId = ngx.var.request_id,
  }
end

local function queue(ev)
  ngx.log(ngx.WARN, "vas waf: ", ev.action, " ", ev.ip, " ", ev.method, " ", ev.uri, " score=", ev.score)
  if not QUEUE then return end
  local s = cjson.encode(ev)
  if not s then return end
  local len = QUEUE:rpush("events", s)
  if len and len > MAX_QUEUE then QUEUE:lpop("events") end
end

local function custom_match(v, cr)
  if cr.kind == "regex" then
    return ngx.re.find(v, cr.value, "ijo") ~= nil
  end
  local lv = v:lower()
  if cr.kind == "equals" then return lv == cr.lvalue end
  return lv:find(cr.lvalue, 1, true) ~= nil
end

-- returns an event to block with, or nil to let the request through
function _M.check(route_id)
  local c = config()
  if not c then return nil end
  local rc = c.routes and c.routes[route_id]
  if not rc or rc.mode == "off" then return nil end

  local uri = ngx.var.uri or ""
  for _, p in ipairs(rc.excludePaths or {}) do
    if uri:sub(1, #p) == p then return nil end
  end

  local cache = {}
  local function values(t)
    local v = cache[t]
    if v == nil then
      if t:sub(1, 7) == "header:" then
        local h = ngx.var["http_" .. t:sub(8):lower():gsub("-", "_")]
        v = h and { h } or {}
      else
        local g = getters[t]
        v = g and g() or {}
      end
      cache[t] = v
    end
    return v
  end

  -- explicit blocklist (geo $vas_waf_blocked): always blocks
  if ngx.var.vas_waf_blocked == "1" then
    return event(route_id, rc, "blocklist", 0, { { id = 0, msg = "client IP is on the blocklist" } })
  end

  -- custom rules first; "allow" skips the rest
  for _, cr in ipairs(rc.custom or {}) do
    local hit
    for _, v in ipairs(values(cr.target)) do
      if custom_match(v, cr) then
        hit = v
        break
      end
    end
    if hit then
      if cr.action == "allow" then return nil end
      local blocking = cr.action == "block" and rc.mode == "block"
      local ev = event(route_id, rc, blocking and "block" or (cr.action == "block" and "detect" or "log"), 0,
        { { id = cr.id, msg = cr.name, target = cr.target, match = hit:sub(1, 120) } })
      if blocking then return ev end
      queue(ev)
    end
  end

  -- built-in rules: anomaly scoring
  local hits, score = {}, 0
  local paranoia = rc.paranoia or 1
  for _, r in ipairs(c.rules or {}) do
    if r.paranoia <= paranoia and not c.disabled_set[r.id] and not rc.excluded_set[r.id] then
      for _, t in ipairs(r.targets) do
        local found
        for _, v in ipairs(values(t)) do
          local from, to = ngx.re.find(v, r.pattern, r.flags)
          if from then
            local s = math.max(1, from - 20)
            found = { id = r.id, msg = r.msg, target = t, match = v:sub(s, math.min(#v, to + 20, s + 119)) }
            break
          end
        end
        if found then
          hits[#hits + 1] = found
          score = score + r.severity
          break
        end
      end
    end
  end

  if score >= (rc.threshold or 5) then
    local ev = event(route_id, rc, rc.mode == "block" and "block" or "detect", score, hits)
    if rc.mode == "block" then return ev end
    queue(ev)
  end
  return nil
end

local PAGE = [==[<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Request blocked</title>
<style>body{margin:0;min-height:100vh;display:grid;place-items:center;background:#f4f5f7;color:#1b1f24;font:16px/1.6 system-ui,sans-serif}
.card{max-width:480px;margin:16px;padding:32px;background:#fff;border:1px solid #dde1e6;border-radius:12px}
h1{font-size:20px;margin:0 0 8px}p{margin:0 0 8px;color:#66707c}code{font-size:13px}
@media (prefers-color-scheme:dark){body{background:#111316;color:#e3e6ea}.card{background:#1c2025;border-color:#2c323b}p{color:#8b939e}}</style>
</head><body><div class="card"><h1>Request blocked</h1>
<p>This request was blocked by the web application firewall.</p>
<p>If you think this is a mistake, contact the site administrator and quote request ID <code>{{id}}</code>.</p>
</div></body></html>
]==]

function _M.deny(ev)
  queue(ev)
  local status = (config() or {}).blockStatus or 403
  if status == 444 then return ngx.exit(444) end -- close the connection without a response
  ngx.status = status
  ngx.header["Cache-Control"] = "no-store"
  ngx.header["X-Request-Id"] = ev.requestId
  local accept = ngx.var.http_accept or ""
  if accept:find("json", 1, true) and not accept:find("html", 1, true) then
    ngx.header["Content-Type"] = "application/json"
    ngx.say(cjson.encode({ error = "blocked", requestId = ev.requestId }))
  else
    ngx.header["Content-Type"] = "text/html; charset=utf-8"
    ngx.say((PAGE:gsub("{{id}}", tostring(ev.requestId or ""))))
  end
  return ngx.exit(status)
end

-- ---------------------------------------------------------------------------
-- event shipping (privileged agent): POST batches to the manager

local MANAGER = (os.getenv("VAS_MANAGER_URL") or "http://127.0.0.1:8080"):gsub("/+$", "")
local TOKEN = os.getenv("VAS_AGENT_TOKEN") or ""

local function post(path, body)
  local scheme, rest = MANAGER:match("^(https?)://(.+)$")
  if not scheme then return nil, "bad VAS_MANAGER_URL" end
  local hostport = rest:match("^([^/]+)")
  local host, port = hostport:match("^%[(.+)%]:?(%d*)$")
  if not host then host, port = hostport:match("^([^:]+):?(%d*)$") end
  port = tonumber(port) or (scheme == "https" and 443 or 80)
  local sock = ngx.socket.tcp()
  sock:settimeout(10000)
  local ok, err = sock:connect(host, port)
  if not ok then return nil, err end
  if scheme == "https" then
    local _, serr = sock:sslhandshake(nil, host, false)
    if serr then sock:close() return nil, serr end
  end
  local _, werr = sock:send(table.concat({
    "POST " .. path .. " HTTP/1.0",
    "Host: " .. host,
    "Connection: close",
    "Authorization: Bearer " .. TOKEN,
    "Content-Type: application/json",
    "Content-Length: " .. #body,
  }, "\r\n") .. "\r\n\r\n" .. body)
  if werr then sock:close() return nil, werr end
  local data, rerr, partial = sock:receive("*a")
  sock:close()
  data = data or partial
  local status = data and tonumber(data:match("^HTTP/%d%.%d (%d%d%d)"))
  if not status then return nil, rerr or "bad response" end
  return status
end

local function ship(premature)
  if premature or not QUEUE then return end
  local batch = {}
  for _ = 1, 500 do
    local s = QUEUE:lpop("events")
    if not s then break end
    batch[#batch + 1] = s
  end
  if #batch == 0 then return end
  local status, err = post("/api/agent/openresty/waf-events", '{"events":[' .. table.concat(batch, ",") .. "]}")
  if not status or status >= 300 then
    ngx.log(ngx.WARN, "vas waf: cannot ship ", #batch, " events: ", err or status)
    for i = #batch, 1, -1 do QUEUE:lpush("events", batch[i]) end -- retry next round, keep order
  end
end

function _M.init_worker()
  if process.type() ~= "privileged agent" or TOKEN == "" then return end
  ngx.timer.every(5, ship)
end

return _M
`;
